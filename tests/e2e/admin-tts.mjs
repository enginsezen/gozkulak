import { chromium } from "playwright";
const b = await chromium.launch();
const p = await (await b.newContext()).newPage();
await p.goto("http://localhost:8080/wp-login.php");
await p.fill("#user_login", "admin"); await p.fill("#user_pass", "admin"); await p.click("#wp-submit");
await p.waitForLoadState("networkidle");
await p.goto("http://localhost:8080/wp-admin/options-general.php?page=gozkulak");
console.log("grup başlıkları:", await p.evaluate(() => [...document.querySelectorAll(".form-table th")].map((t) => t.textContent.trim()).filter((t) => /Sesli|Görme|Okuma/.test(t)).join(" | ")));
const box = p.locator('input[name="gozkulak_settings[features][text_to_speech]"]');
console.log("kutu var mı:", await box.count(), "| işaretli mi:", await box.isChecked());
await box.uncheck();
await p.click("#submit");
await p.waitForLoadState("networkidle");
console.log("kaydedildi, işaretli mi:", await p.locator('input[name="gozkulak_settings[features][text_to_speech]"]').isChecked());
await p.goto("http://localhost:8080/?p=6");
await p.waitForTimeout(800);
console.log("kapalıyken panelde sesli okuma var mı:", await p.evaluate(() => !!document.querySelector("gozkulak-root").shadowRoot.querySelector(".gk-speech")), "| config:", await p.evaluate(() => JSON.parse(document.getElementById("gozkulak-config").textContent).features.includes("text_to_speech")));
await p.goto("http://localhost:8080/wp-admin/options-general.php?page=gozkulak");
await p.locator('input[name="gozkulak_settings[features][text_to_speech]"]').check();
await p.click("#submit");
await p.waitForLoadState("networkidle");
console.log("geri açıldı:", await p.locator('input[name="gozkulak_settings[features][text_to_speech]"]').isChecked());
await b.close();
